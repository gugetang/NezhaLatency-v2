#!/usr/bin/env python3
"""Build NezhaLatency.js (script-src version) from NezhaLatency.html.

Usage: python3 build-js.py
Reads NezhaLatency.html in the same directory and writes NezhaLatency.js.
The .js file is a self-contained IIFE: it injects the CSS + HTML nodes,
then runs the same 3 script blocks in order (ECharts loader, CONFIG, main).
That makes the project loadable from Nezha v2 custom_code with one line:
  <script src="https://cdn.jsdelivr.net/gh/gugetang/NezhaLatency-v2@main/NezhaLatency.js"></script>
Config override (optional, before the script tag):
  <script>window.NezhaLatencyConfig = { refreshSec: 30 };</script>
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "NezhaLatency.html"
DST = HERE / "NezhaLatency.js"

text = SRC.read_text(encoding="utf-8")

m_style = re.search(r"<style>(.*?)</style>", text, re.S)
m_scripts = re.findall(r"<script>(.*?)</script>", text, re.S)
if not m_style or len(m_scripts) != 3:
    sys.exit(f"unexpected structure: style={bool(m_style)} scripts={len(m_scripts)}")

css = m_style.group(1).strip("\n")
# HTML nodes: between </style> and the first <script>
html_start = m_style.end()
html_end = text.find("<script>", html_start)
html = text[html_start:html_end].strip()

echarts_loader, config_js, main_js = [s.strip("\n") for s in m_scripts]

header = """// NezhaLatency v2 — script-src version, generated from NezhaLatency.html
// Generated by build-js.py — do not edit by hand, edit NezhaLatency.html and rebuild.
// Load from Nezha v2 custom_code with one line:
//   <script src="https://cdn.jsdelivr.net/gh/gugetang/NezhaLatency-v2@main/NezhaLatency.js"></script>
// Optional config override, before that line:
//   <script>window.NezhaLatencyConfig = { refreshSec: 30 };</script>
(function () {
  'use strict';
  // Avoid double injection when custom_code is re-applied in the same page.
  if (document.getElementById('nl-fab')) return;
  var VERSION = 'NezhaLatency-v2';
  var CSS = %s;
  var HTML = %s;
  function inject() {
    if (!document.getElementById('nezha-latency-style')) {
      var st = document.createElement('style');
      st.id = 'nezha-latency-style';
      st.textContent = CSS;
      document.head.appendChild(st);
    }
    var tmp = document.createElement('div');
    tmp.innerHTML = HTML;
    while (tmp.firstChild) document.body.appendChild(tmp.firstChild);
  }
  function run() {
    inject();
%s
%s
%s
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', run);
  } else {
    run();
  }
})();
""" % (
    json.dumps(css, ensure_ascii=False),
    json.dumps(html, ensure_ascii=False),
    echarts_loader,
    config_js,
    main_js,
)

DST.write_text(header, encoding="utf-8")
print(f"wrote {DST} ({DST.stat().st_size} bytes)")
